"""Reading the command a ``uv pip compile`` output file records about itself. Pure: no I/O.

``uv pip compile ... -o requirements.txt`` writes the command that produced it into the file's
header, after the line ``# This file was autogenerated by uv via the following command:``. The
bot regenerates such a file with that command, so the header is **text of a pull request** and
is never run as written. :func:`parse_header` accepts exactly one shape,

    uv pip compile <input> [flags] -o <output>

with the flags of :data:`FLAGS` and nothing else, and the input and output must be the two paths
the default branch's policy configured. The result is an argument list for a program started
without a shell, so nothing in the header can be interpreted as shell syntax either.
"""

from __future__ import annotations

import re
import shlex
from dataclasses import dataclass

HEADER_MARKER = "# This file was autogenerated by uv via the following command:"
# The header is the first lines of the file; anything further down is the requirements.
MAX_HEADER_LINES = 20
MAX_TOKENS = 24
_TOKEN = re.compile(r"^[A-Za-z0-9._/@+=:-]+\Z")
_VERSION = re.compile(r"^[0-9]+(?:\.[0-9]+){0,2}\Z")
_PLATFORM = re.compile(r"^[a-z0-9][a-z0-9_.-]*\Z")

# The switches that take no value, and the ones that take one with the rule for its value.
SWITCHES = frozenset({"--generate-hashes", "--universal"})
VALUED: dict[str, re.Pattern[str]] = {
    "--python-version": _VERSION,
    "--python-platform": _PLATFORM,
}
OUTPUT_FLAGS = frozenset({"-o", "--output-file"})
FLAGS: tuple[str, ...] = (*sorted(SWITCHES), *VALUED, "-o/--output-file")


class CompileCommandError(ValueError):
    """The header does not record a command the bot is willing to run; the text says why."""


@dataclass(frozen=True, slots=True)
class CompileCommand:
    """A validated ``uv pip compile`` invocation.

    ``arguments`` are the tokens after ``uv`` in the order the header recorded them: uv writes
    its command line back into the output's header, so the same order keeps the header, and so
    the file, stable from one run to the next.
    """

    input: str
    output: str
    arguments: tuple[str, ...]


def header_command(text: str) -> str | None:
    """The command line the header of ``text`` records, or ``None`` when there is none."""
    lines = text.splitlines()[:MAX_HEADER_LINES]
    for index, line in enumerate(lines):
        if line.strip() != HEADER_MARKER:
            continue
        following = lines[index + 1] if index + 1 < len(lines) else ""
        if not following.startswith("#"):
            return None
        return following[1:].strip() or None
    return None


def parse_command(command: str, input_path: str, output_path: str) -> CompileCommand:
    """Validate ``command`` against the configured paths, or raise :class:`CompileCommandError`."""
    try:
        tokens = shlex.split(command, posix=True)
    except ValueError as exc:
        raise CompileCommandError(f"the command cannot be split into words: {exc}") from None
    if len(tokens) > MAX_TOKENS:
        raise CompileCommandError(f"the command has more than {MAX_TOKENS} words")
    for token in tokens:
        if not _TOKEN.match(token):
            raise CompileCommandError(f"the word {token!r} has characters the bot does not accept")
    if tokens[:3] != ["uv", "pip", "compile"]:
        raise CompileCommandError("the command is not 'uv pip compile'")
    arguments = tokens[1:]
    inputs, output = _scan(arguments[2:])
    if inputs != [input_path]:
        raise CompileCommandError(
            f"the input is {', '.join(map(repr, inputs)) or 'missing'}, "
            f"the policy configures {input_path!r}"
        )
    if output != output_path:
        raise CompileCommandError(
            f"the output is {output!r}, the policy configures {output_path!r}"
        )
    return CompileCommand(input_path, output_path, tuple(arguments))


def _scan(words: list[str]) -> tuple[list[str], str | None]:
    """Split the words after ``uv pip compile`` into the inputs and the output."""
    inputs: list[str] = []
    output: str | None = None
    seen: set[str] = set()
    index = 0
    while index < len(words):
        word = words[index]
        index += 1
        if not word.startswith("-"):
            inputs.append(word)
            continue
        flag = "-o" if word in OUTPUT_FLAGS else word
        if flag in seen:
            raise CompileCommandError(f"the flag {word} is given twice")
        if flag in SWITCHES:
            seen.add(flag)
        elif flag in VALUED or flag == "-o":
            if index >= len(words) or words[index].startswith("-"):
                raise CompileCommandError(f"the flag {word} has no value")
            value = words[index]
            index += 1
            if flag == "-o":
                output = value
            elif not VALUED[flag].match(value):
                raise CompileCommandError(f"the value {value!r} of {word} is not accepted")
            seen.add(flag)
        else:
            raise CompileCommandError(
                f"the flag {word} is not allowed (allowed: {', '.join(FLAGS)})"
            )
    return inputs, output
