def test_no_option_means_no_compiled_file() -> None:
    parsed = LockfilesOptions.model_validate({})

    assert parsed.uv_pip_compile == []
    assert parsed.uv_pip_outputs() == {}


def test_an_entry_names_an_input_and_an_output_exactly() -> None:
    parsed = options(entry(), entry("a/requirements.in", "a/requirements.txt"))

    assert set(parsed.uv_pip_outputs()) == {OUTPUT, "a/requirements.txt"}
    assert parsed.uv_pip_outputs()[OUTPUT].input == INPUT


@pytest.mark.parametrize(
    ("raw", "message"),
    [
        (entry(output_path="*.txt"), "pattern"),
        (entry(output_path="../r.txt"), "'..' segment"),
        (entry(output_path="/etc/r.txt"), "absolute"),
        (entry(output_path=".github/workflows/r.txt"), r"\.github"),
        (entry(output_path=".github/lktec-bot.yml"), "policy file"),
        (entry(input_path=".github/r.in"), r"\.github"),
        (entry(output_path="uv.lock"), "lock file"),
        (entry(output_path="x/packages.lock.json"), "lock file"),
        (entry(input_path="a bé.in"), "character"),
        (entry(OUTPUT, OUTPUT), "different files"),
        ({"input": INPUT}, "output"),
        ({**entry(), "extra": "1"}, "Extra inputs"),
    ],
)
def test_a_bad_entry_makes_the_options_invalid(raw: dict[str, str], message: str) -> None:
    with pytest.raises(ValidationError, match=message):
        options(raw)


def test_an_output_cannot_be_listed_twice_or_belong_to_a_generator() -> None:
    with pytest.raises(ValidationError, match="listed twice"):
        options(entry(), entry("other.in", OUTPUT))
    with pytest.raises(ValidationError, match="also a derived path"):
        options(
            entry(),
            derived=[{"name": "n", "run": "make", "paths": [OUTPUT]}],
        )
    with pytest.raises(ValidationError, match="generated by the policy itself"):
        options(
            entry(),
            derived=[{"name": "n", "run": "make", "paths": [INPUT]}],
        )


def test_the_number_of_entries_is_bounded() -> None:
    many = [entry(f"d{n}/r.in", f"d{n}/r.txt") for n in range(9)]

    assert len(options(*many[:8]).uv_pip_compile) == 8
    with pytest.raises(ValidationError, match="at most 8"):
        options(*many)


def test_the_policy_validates_with_the_option_and_rejects_a_bad_one() -> None:
    assert validate_policy(POLICY).modules["lockfiles"].options["uv-pip-compile"]
    with pytest.raises(Exception, match="uv-pip-compile"):
        validate_policy(POLICY.replace(OUTPUT, "uv.lock"))


# -- the allow-list -------------------------------------------------------------------------


def test_a_configured_output_is_admitted_exactly() -> None:
    declared = options(entry())

    verdict = admit(OUTPUT, 10, declared)

    assert (verdict.kind, verdict.refused, verdict.left_out) == (Kind.UV_PIP, False, False)
    for other in (
        "requirements.txt",
        f"x/{OUTPUT}",
        f"{OUTPUT}.bak",
        INPUT,
        "docs/requirements.txt",
    ):
        refused = admit(other, 10, declared)
        assert refused.refused
        assert "uv-pip-compile[].output" in refused.problem


def test_without_the_option_requirements_txt_is_refused() -> None:
    assert admit(OUTPUT, 10, options()).refused
    assert admit("requirements.txt", 10, LockfilesOptions.model_validate({})).refused


def test_the_ecosystems_and_paths_options_do_not_touch_a_configured_output() -> None:
    declared = options(entry(), ecosystems=["dotnet"], paths=["services"])

    assert admit(OUTPUT, 10, declared).kind is Kind.UV_PIP
    assert not admit(OUTPUT, 10, declared).left_out


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        ("../requirements.txt", "'..' segment"),
        ("/etc/requirements.txt", "absolute"),
        (".github/workflows/requirements.txt", "workflows"),
        (".git/requirements.txt", "points into .git"),
        ("a//requirements.txt", "empty"),
    ],
)
def test_a_configured_output_still_goes_through_every_path_check(path: str, reason: str) -> None:
    # The options model refuses such a declaration; the allow-list must not rely on that.
    forged = LockfilesOptions.model_construct(
        ecosystems=[],
        paths=[],
        derived=[],
        uv_pip_compile=[],
    )
    forged.uv_pip_compile = [
        type(options(entry()).uv_pip_compile[0]).model_construct(input="x.in", output=path)
    ]

    verdict = admit(path, 1, forged)

    assert verdict.refused
    assert reason in verdict.problem or ".github" in verdict.problem


def test_an_oversized_compiled_file_is_refused() -> None:
    declared = options(entry())
    too_large = allowlist.MAX_DERIVED_FILE_BYTES + 1

    assert admit(OUTPUT, allowlist.MAX_DERIVED_FILE_BYTES, declared).kind is Kind.UV_PIP
    assert (
        "compiled requirements file is larger than 2 MiB"
        in admit(OUTPUT, too_large, declared).problem
    )


# -- the use case ---------------------------------------------------------------------------

UV = "/opt/uv/bin/uv"
ROOT = Path("/work/pr")


@dataclass
class FakeCheckout:
    policy_text: str | None = POLICY
    files: dict[str, bytes] = field(default_factory=dict)

    def trusted_file(self, path: str) -> str | None:
        assert path == POLICY_PATH
        return self.policy_text

    def head(self, path: str) -> bytes | None:
        return self.files.get(path)


@dataclass
class FakeRunner:
    checkout: FakeCheckout
    result: CommandResult = field(default_factory=lambda: CommandResult(0))
    rewrite: dict[str, bytes] = field(default_factory=dict)
    vanish: bool = False
    ran: list[tuple[list[str], Path, int, dict[str, str]]] = field(default_factory=list)

    def run(
        self, argv: Sequence[str], cwd: Path, timeout_seconds: int, env: Mapping[str, str]
    ) -> CommandResult:
        self.ran.append((list(argv), cwd, timeout_seconds, dict(env)))
        if self.result.exit_code == 0:
            self.checkout.files.update(self.rewrite)
            if self.vanish:
                del self.checkout.files[OUTPUT]
        return self.result


@dataclass
class FakeSink:
    added: list[dict[str, bytes]] = field(default_factory=list)

    def add(self, files: Mapping[str, bytes]) -> None:
        self.added.append(dict(files))


class Case:
    def __init__(
        self, policy_text: str | None = POLICY, env: Mapping[str, str] | None = None
    ) -> None:
        self.old = header().encode()
        self.new = header().replace("7.0.0", "7.1.0").encode()
        self.checkout = FakeCheckout(policy_text, {OUTPUT: self.old, INPUT: b"coverage\n"})
        self.runner = FakeRunner(self.checkout, rewrite={OUTPUT: self.new})
        self.sink = FakeSink()
        self.uv_pip = UvPip(
            self.checkout, self.runner, self.sink, env or {"PATH": "/usr/bin"}, UV, ROOT
        )

    def run(self) -> UvPipReport:
        return self.uv_pip.run()


def test_the_recorded_command_runs_without_a_shell_and_its_output_is_handed_over() -> None:
    case = Case()

    report = case.run()

    assert report.decision is UvPipDecision.GENERATED
    assert report.files == (OUTPUT,)
    assert report.handed_over
    assert case.sink.added == [{OUTPUT: case.new}]
    argv, cwd, timeout, _ = case.runner.ran[0]
    # The uv the caller named, then the recorded words in their recorded order.
    assert argv == [UV, *COMMAND.split()[1:]]
    assert cwd == ROOT
    assert timeout == 300


def test_the_environment_carries_no_credential() -> None:
    env = {
        "PATH": "/usr/bin",
        "GITHUB_TOKEN": "t",
        "GH_TOKEN": "t",
        "LKTEC_BOT_PRIVATE_KEY": "k",
        "UV_PYTHON_DOWNLOADS": "never",
    }
    case = Case(env=env)

    case.run()

    assert case.runner.ran[0][3] == {"PATH": "/usr/bin", "UV_PYTHON_DOWNLOADS": "never"}


def test_a_file_that_already_matches_is_unchanged() -> None:
    case = Case()
    case.runner.rewrite = {OUTPUT: case.old}

    report = case.run()

    assert report.decision is UvPipDecision.UNCHANGED
    assert case.sink.added == []


