# -- recognition ------------------------------------------------------------------------------


def pull(author: str, ref: str = "renovate/x-1.x", repo: str = "acme/widgets") -> PullRequest:
    return PullRequest(
        number=1,
        html_url="",
        state="open",
        draft=False,
        head_sha="0" * 40,
        author_login=author,
        head_ref=ref,
        head_repo=repo,
    )


@pytest.mark.parametrize("renovate", [True, False])
def test_dependabot_is_always_recognised(renovate: bool) -> None:
    result = recognise(
        pull("dependabot[bot]", "dependabot/pip/x"), "acme/widgets", options(renovate=renovate)
    )

    assert result == Recognition(UpdateSource.DEPENDABOT)


def test_renovate_is_recognised_only_when_the_policy_turns_it_on() -> None:
    renovate = pull("renovate[bot]")

    assert recognise(renovate, "acme/widgets", options()) == Recognition(
        None, "not opened by dependabot[bot]"
    )
    assert recognise(renovate, "ACME/Widgets", options(renovate=True)) == Recognition(
        UpdateSource.RENOVATE
    )


@pytest.mark.parametrize(
    ("pull_request", "reason"),
    [
        (pull("someone"), "not opened by dependabot[bot] or renovate[bot]"),
        (pull("renovate"), "not opened by dependabot[bot] or renovate[bot]"),
        (pull("renovate-bot[bot]"), "not opened by dependabot[bot] or renovate[bot]"),
        (pull("Renovate[bot]"), "not opened by dependabot[bot] or renovate[bot]"),
        (pull("renovate[bot]", ref="main"), "renovate[bot] pull request not on a renovate/ branch"),
        (
            pull("renovate[bot]", ref="x/renovate/y"),
            "renovate[bot] pull request not on a renovate/ branch",
        ),
        (
            pull("renovate[bot]", repo="fork/widgets"),
            "renovate[bot] pull request from another repository",
        ),
        (pull("renovate[bot]", repo=""), "renovate[bot] pull request from another repository"),
    ],
)
def test_anything_else_is_not_a_renovate_pull_request(
    pull_request: PullRequest, reason: str
) -> None:
    assert recognise(pull_request, "acme/widgets", options(renovate=True)) == Recognition(
        None, reason
    )


def test_each_source_is_read_its_own_way() -> None:
    dependabot = "Bump ruff from 0.13.0 to 0.13.1"

    assert classify_update(UpdateSource.DEPENDABOT, dependabot, "").kind is PATCH
    assert classify_update(UpdateSource.RENOVATE, "u", STUDYLIFE_PIN).kind is PATCH
    # a Dependabot title means nothing to the Renovate reader without its table, and back
    assert classify_update(UpdateSource.RENOVATE, "update x to v1.0.1", "").kind is None
    assert classify_update(UpdateSource.DEPENDABOT, "u", STUDYLIFE_PIN).kind is None


def test_a_table_at_the_very_end_of_the_body_is_read() -> None:
    text = "| Package | Update | Change |\n|---|---|---|\n| x | minor | `1.0.0` → `1.1.0` |"

    assert classify_renovate("u", text).kind is MINOR
