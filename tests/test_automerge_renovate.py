PATCH, MINOR, MAJOR, DIGEST = (
    UpdateKind.PATCH,
    UpdateKind.MINOR,
    UpdateKind.MAJOR,
    UpdateKind.DIGEST,
)

FOOTER = (
    "\n---\n\n### Configuration\n\n📅 **Schedule**: (UTC)\n\n"
    "🚦 **Automerge**: Disabled by config. Please merge this manually once you are satisfied.\n\n"
    "♻ **Rebasing**: Whenever PR is behind base branch, or you tick the rebase/retry checkbox.\n\n"
    "---\n\n - [ ] <!-- rebase-check -->If you want to rebase/retry this PR, check this box\n\n"
    "---\n\nThis PR was generated by [Mend Renovate](https://mend.io/renovate/).\n"
    "<!--renovate-debug:eyJjcmVhdGVkSW5WZXIiOiI0NC4yMjguMCJ9-->\n"
)


def body(*rows: str, header: str = "| Package | Update | Change |", notes: str = "") -> str:
    separator = "|" + "---|" * (header.count("|") - 1)
    table = "\n".join([header, separator, *rows])
    return f"This PR contains the following updates:\n\n{table}\n\n{notes}{FOOTER}"


def options(**values: object) -> AutomergeOptions:
    return AutomergeOptions.model_validate(values)


