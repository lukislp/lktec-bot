@pytest.mark.parametrize(
    ("text", "kind", "names"),
    [
        (REDIS_EXPORTER, MINOR, ("oliver006/redis_exporter",)),
        (REDIS_DIGEST, DIGEST, ("redis",)),
        (LOKI, PATCH, ("grafana/loki",)),
        (STUDYLIFE_PIN, PATCH, ("lukislp/studylife",)),
    ],
)
def test_real_renovate_bodies(text: str, kind: UpdateKind, names: tuple[str, ...]) -> None:
    result = classify_renovate("chore(k8s): update something", text)

    assert result.kind is kind
    assert result.names == names
    assert result.grouped is False
    assert result.problem is None


@pytest.mark.parametrize(
    ("update", "change", "kind"),
    [
        # the studylife.version pin of studylife-app (regex manager, semver, v prefix)
        ("patch", "`v3.34.4` → `v3.34.5`", PATCH),
        ("minor", "`v3.34.5` → `v3.35.0`", MINOR),
        ("major", "`v3.35.0` → `v4.0.0`", MAJOR),
        # the older ASCII arrow, and a change wrapped in a link to the diff
        ("patch", "`1.0.0` -> `1.0.1`", PATCH),
        (
            "minor",
            "[`8.56.0` -> `8.57.0`](https://renovatebot.com/diffs/npm/eslint/8.56.0/8.57.0)",
            MINOR,
        ),
        # PEP 440 and Docker shapes
        ("minor", "`1.4.1.post1` → `1.5.0`", MINOR),
        ("minor", "`3.13-slim` → `3.14-slim`", MINOR),
        # what Renovate declares and what the versions say: the larger one counts
        ("patch", "`1.0.0` → `2.0.0`", MAJOR),
        ("major", "`1.0.0` → `1.0.1`", MAJOR),
        ("digest", "`8.10.3-alpine` → `8.10.3-alpine`", PATCH),
        ("digest", "`v4` → `v5`", MAJOR),
        # the update type is matched without regard to case or backticks
        ("Minor", "`1.0.0` → `1.1.0`", MINOR),
        ("`patch`", "`1.0.0` → `1.0.1`", PATCH),
    ],
)
def test_declared_and_read_kind(update: str, change: str, kind: UpdateKind) -> None:
    result = classify_renovate("update x", body(f"| x | {update} | {change} |"))

    assert result.kind is kind
    assert result.problem is None


@pytest.mark.parametrize(
    ("row", "problem"),
    [
        ("| x | pin | `^1.2.3` → `1.2.3` |", "x: update type 'pin' is manual"),
        ("| x | pinDigest | `v4` → `11bd719` |", "x: update type 'pinDigest' is manual"),
        ("| x | rollback | `2.0.0` → `1.9.0` |", "x: update type 'rollback' is manual"),
        ("| x | replacement | `1.0.0` → `1.0.0` |", "x: update type 'replacement' is manual"),
        ("| x | bump | `^1.0.0` → `^1.0.1` |", "x: update type 'bump' is manual"),
        (
            "| x | lockFileMaintenance | `1.0.0` → `1.0.1` |",
            "x: update type 'lockFileMaintenance' is manual",
        ),
        ("| x |  | `1.0.0` → `1.0.1` |", "x: update type '' is manual"),
        ("| x | patch | `1.0.0` |", "x: no old and new value in the change"),
        ("| x | patch | → `11bd719` |", "x: no old and new value in the change"),
        ("| x | patch | 1.0.0 → 1.0.1 |", "x: no old and new value in the change"),
        ("| x | minor | `^1.2.3` → `^1.3.0` |", "version not understood: x ^1.2.3 to ^1.3.0"),
        ("| x | patch | `latest` → `stable` |", "version not understood: x latest to stable"),
        # a digest that is not hex is not a digest
        ("| x | digest | `abc` → `def` |", "version not understood: x abc to def"),
        # hex is only a digest when Renovate says so
        ("| x | patch | `71885d8` → `7958cfb` |", "version not understood: x 71885d8 to 7958cfb"),
        (
            "| x | patch | `1.0.0` → `1.0.1` | extra |",
            "a row of the update table has 4 cells, not 3",
        ),
        ("| | patch | `1.0.0` → `1.0.1` |", "a row of the update table names no package"),
    ],
)
def test_rows_that_cannot_be_read_are_manual(row: str, problem: str) -> None:
    result = classify_renovate("update x", body(row))

    assert result.kind is None
    assert result.problem == problem
    assert evaluate(result, options(majors="auto")).arm is False


def test_a_table_without_an_update_column_is_read_from_the_change() -> None:
    header = "| Package | Change | Age | Confidence |"

    patch = classify_renovate("u", body("| x | `1.0.0` → `1.0.1` | a | b |", header=header))
    hexes = classify_renovate("u", body("| x | `71885d8` → `7958cfb` | a | b |", header=header))

    assert patch.kind is PATCH
    assert hexes.kind is None  # without Renovate's word for it, hex is not a digest


def test_a_table_with_more_columns_in_another_order() -> None:
    header = "| Package | Type | Change | Update | Pending |"
    row = "| [eslint](https://eslint.org) | devDependencies | `8.56.0` -> `8.57.0` | minor | |"

    assert classify_renovate("u", body(row, header=header)).kind is MINOR


def test_an_empty_table_is_manual() -> None:
    result = classify_renovate("u", body())

    assert result.kind is None
    assert result.problem == "the update table lists no updates"


def test_a_table_needs_its_separator_line() -> None:
    text = "| Package | Update | Change |\n| x | patch | `1.0.0` → `1.0.1` |\n"

    result = classify_renovate("update x to v1.0.1", text)

    assert result.kind is None
    assert result.problem == "no update table and no version change in the title"


def test_crlf_bodies_are_read() -> None:
    assert classify_renovate("u", LOKI.replace("\n", "\r\n")).kind is PATCH


# -- groups -----------------------------------------------------------------------------------


def test_a_group_of_minor_patch_and_digest_updates_is_as_severe_as_its_largest_member() -> None:
    result = classify_renovate(
        "chore(k8s): update kubernetes image tags",
        body(
            "| [redis](https://hub.docker.com/_/redis) | digest | `71885d8` → `7958cfb` |",
            "| oliver006/redis_exporter | minor | `v1.96.0` → `v1.97.0` |",
            "| grafana/loki | patch | `3.7.9` → `3.7.10` |",
        ),
    )

    assert result.grouped is True
    assert result.kind is MINOR
    assert result.names == ("redis", "oliver006/redis_exporter", "grafana/loki")
    assert evaluate(result, options()) == Eligibility(True, "minor update (group)", MINOR)


def test_a_group_with_one_major_is_a_major() -> None:
    result = classify_renovate(
        "update all",
        body("| a | patch | `1.0.0` → `1.0.1` |", "| b | major | `1.0.0` → `2.0.0` |"),
    )

    assert result.kind is MAJOR
    assert evaluate(result, options()).arm is False


def test_a_group_with_one_unreadable_member_is_manual_as_a_whole() -> None:
    result = classify_renovate(
        "update all",
        body("| a | patch | `1.0.0` → `1.0.1` |", "| b | pin | `^1.0.0` → `1.0.0` |"),
    )

    assert result.kind is None
    assert result.problem == "b: update type 'pin' is manual"
    assert result.names == ("a", "b")


def test_a_group_with_one_excluded_member_is_skipped_as_a_whole() -> None:
    result = classify_renovate(
        "update all",
        body(
            "| ghcr.io/fluxcd/source-controller | patch | `v1.7.0` → `v1.7.1` |",
            "| grafana/loki | patch | `3.7.9` → `3.7.10` |",
        ),
    )

    eligibility = evaluate(result, options(exclude=["GHCR.io/fluxcd/source-controller"]))

    assert eligibility == Eligibility(
        False, "excluded dependency: ghcr.io/fluxcd/source-controller", excluded=True
    )


def test_an_excluded_member_of_an_unreadable_group_is_still_excluded() -> None:
    result = classify_renovate("update all", body("| pymammotion | pin | `^1` → `1.0.0` |"))

    assert evaluate(result, options(exclude=["pymammotion"])).excluded is True


def test_without_any_name_and_an_exclude_list_it_is_excluded() -> None:
    result = classify_renovate("update x to v2", "")

    eligibility = evaluate(result, options(exclude=["x"]))

    assert eligibility.excluded is True
    assert eligibility.arm is False


